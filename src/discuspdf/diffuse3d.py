"""Execute an independently validated DISCUS macro that emits 3D data.

No unverified DISCUS 3D command syntax is generated by this module.
A macro and its referenced files must first be validated with DISCUS_SUITE.

Output validation is deliberately split into two layers:

* **Structural** (this module): the produced ``diffuse.h5`` can be opened as
  HDF5, and — when the caller supplies an :class:`OutputSpec` — the expected
  datasets exist, are numeric, have the expected shape, and contain finite
  values.  Structural success is recorded as status ``complete``.
* **Physical** (caller's responsibility): units, Bragg handling, coordinate
  system, and quantitative calibration of native DISCUS 3D output are *not*
  verified here.  When no ``OutputSpec`` is supplied, a structurally valid file
  is recorded as ``produced_unverified`` — never as scientifically complete.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import hashlib
import json
import os
import re
import shutil
import subprocess
import uuid

import numpy as np

# Definitive engine-failure markers in stdout/stderr.  PGPLOT/X11 noise such as
# "xdpyinfo: unable to open display" or "pgxwin_server: cannot connect" is
# harmless for headless macro runs and must NOT be treated as fatal.
_ENGINE_ERROR_PATTERN = re.compile(
    r"(?im)\b(?:unknown command|fatal error|segmentation fault|error\s*:)",
)


@dataclass(frozen=True)
class OutputSpec:
    """Declarative, user-supplied structural validation of ``diffuse.h5``.

    All dataset paths are relative to the HDF5 root, as accepted by h5py
    (e.g. ``"/intensity"``).  No DISCUS layout is assumed: inspect the actual
    file and supply the real paths.  ``expected_shape`` is optional; when
    omitted, dataset presence, numeric type, 3D intensity / 1D axis
    dimensionality, axis-length consistency, and finiteness are still checked.
    """
    intensity_dataset: str
    q_datasets: tuple[str, str, str]
    expected_shape: tuple[int, int, int] | None = None

    def __post_init__(self) -> None:
        if not self.intensity_dataset or len(self.q_datasets) != 3:
            raise ValueError("OutputSpec requires an intensity dataset and three Q dataset paths")
        if any(not path for path in (self.intensity_dataset, *self.q_datasets)):
            raise ValueError("OutputSpec dataset paths must be nonempty")
        if self.expected_shape is not None:
            if len(self.expected_shape) != 3 or any(type(n) is not int or n < 1 for n in self.expected_shape):
                raise ValueError("expected_shape must be three positive integers")


@dataclass(frozen=True)
class Diffuse3DRun:
    directory: Path

    def load_volume(self, *, intensity_dataset: str, q_datasets: tuple[str, str, str],
                    coordinate_system: str, units: str, preprocessing: tuple[str, ...]):
        from .volume import read_hdf5_volume
        from .reciprocal import ReciprocalVolume
        data_path = self.directory / "diffuse.h5"
        intensity, axes = read_hdf5_volume(data_path, intensity_dataset, q_datasets)
        return ReciprocalVolume(intensity, axes, coordinate_system, units,
                                preprocessing=preprocessing,
                                metadata={"source": str(data_path)})


def _validate_hdf5_output(path: Path, spec: OutputSpec | None) -> dict:
    """Structural validation of a produced ``diffuse.h5``.

    Returns a small JSON-serializable report.  Raises ``ValueError`` with a
    specific message when the file is not a usable HDF5 volume.  This checks
    file structure only — never physical correctness.
    """
    import h5py
    if not path.is_file() or path.stat().st_size == 0:
        raise ValueError(f"Output file is missing or empty: {path.name}")
    if not h5py.is_hdf5(path):
        raise ValueError(f"Output file is not a valid HDF5 file: {path.name}")
    report: dict = {"valid_hdf5": True}
    if spec is None:
        return report
    with h5py.File(path, "r") as file:
        for label in ("intensity", *("q0", "q1", "q2")):
            key = spec.intensity_dataset if label == "intensity" else spec.q_datasets[int(label[1])]
            if key not in file:
                raise ValueError(f"Expected dataset not found in {path.name}: {key}")
        intensity = np.asarray(file[spec.intensity_dataset], dtype=float)
        if intensity.ndim != 3:
            raise ValueError(f"Intensity dataset {spec.intensity_dataset!r} is {intensity.ndim}D, expected 3D")
        if spec.expected_shape is not None and intensity.shape != spec.expected_shape:
            raise ValueError(f"Intensity shape {intensity.shape} != expected {spec.expected_shape}")
        if not np.all(np.isfinite(intensity)):
            raise ValueError(f"Intensity dataset {spec.intensity_dataset!r} contains NaN/Inf values")
        q_axes = []
        for key in spec.q_datasets:
            axis = np.asarray(file[key], dtype=float)
            if axis.ndim != 1:
                raise ValueError(f"Q dataset {key!r} is {axis.ndim}D, expected 1D")
            if not np.all(np.isfinite(axis)):
                raise ValueError(f"Q dataset {key!r} contains NaN/Inf values")
            q_axes.append(axis)
        for i, axis in enumerate(q_axes):
            if len(axis) != intensity.shape[i]:
                raise ValueError(f"Q axis {i} length {len(axis)} does not match intensity shape {intensity.shape[i]}")
    report["intensity_shape"] = list(intensity.shape)
    report["q_axis_lengths"] = [len(a) for a in q_axes]
    return report


class Diffuse3DRunner:
    """Run an already-verified 3D macro in an isolated directory.

    The caller must supply all required input files and a macro that writes
    diffuse.h5. No Bragg subtraction or quantitative normalization is assumed.
    """
    def __init__(self, runs_directory="runs_3d",
                 launcher=("discus_suite", "-noautorun", "-macro"),
                 timeout_seconds=3600):
        self.runs_directory = Path(runs_directory)
        self.launcher = tuple(launcher)
        self.timeout_seconds = timeout_seconds
        if not self.launcher or timeout_seconds <= 0:
            raise ValueError("Invalid launcher or timeout")

    def prepare(self, macro: str | Path, assets: tuple[str | Path, ...] = ()) -> Diffuse3DRun:
        macro = Path(macro).expanduser().resolve()
        if not macro.is_file():
            raise FileNotFoundError(macro)
        self.runs_directory.mkdir(parents=True, exist_ok=True)
        directory = self.runs_directory / uuid.uuid4().hex
        directory.mkdir()
        shutil.copy2(macro, directory / "run.mac")
        hashes = {"run.mac": hashlib.sha256((directory / "run.mac").read_bytes()).hexdigest()}
        for asset in assets:
            source = Path(asset).expanduser().resolve()
            if not source.is_file() or source.name in ("run.mac", "diffuse.h5"):
                raise ValueError(f"Invalid input asset: {source}")
            if source.name in hashes:
                raise ValueError(f"Duplicate input asset: {source.name}")
            dest = directory / source.name
            shutil.copy2(source, dest)
            hashes[source.name] = hashlib.sha256(dest.read_bytes()).hexdigest()
        (directory / "inputs.json").write_text(json.dumps(hashes, indent=2))
        (directory / "status.json").write_text('{"status": "prepared"}\n')
        return Diffuse3DRun(directory)

    def _status(self, run: Diffuse3DRun, state: str, **details: object) -> None:
        (run.directory / "status.json").write_text(
            json.dumps({"status": state, **details}, indent=2), encoding="utf-8"
        )

    def _preflight(self, run: Diffuse3DRun) -> None:
        """Verify staged inputs before launching DISCUS.

        Any failure is recorded as a ``failed`` status (no engine process was
        started) and re-raised, so a run directory never stays ``prepared``
        after an attempted execution.
        """
        def fail(exc: Exception) -> None:
            self._status(run, "failed", reason=f"Preflight check failed: {exc}",
                        engine_started=False)
            raise exc

        try:
            hashes = json.loads((run.directory / "inputs.json").read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            fail(ValueError(f"inputs.json is missing or unreadable: {exc}"))
        if "run.mac" not in hashes:
            fail(ValueError("run.mac hash missing from inputs.json"))
        for name, digest in hashes.items():
            path = run.directory / name
            if not path.is_file():
                fail(ValueError(f"Staged input is missing: {name}"))
            if hashlib.sha256(path.read_bytes()).hexdigest() != digest:
                fail(ValueError(f"Staged input was modified after preparation: {name}"))
        if not (run.directory / "run.mac").is_file():
            fail(FileNotFoundError("Prepared macro run.mac is missing"))
        output = run.directory / "diffuse.h5"
        if output.exists():
            fail(FileExistsError(f"Refusing to overwrite existing output: {output}; "
                                 "delete it or use a new run directory to rerun"))

    def execute(self, run: Diffuse3DRun, output_spec: OutputSpec | None = None) -> Diffuse3DRun:
        """Execute the exact staged macro and validate the produced file.

        Status transitions: ``prepared`` → ``running`` → ``complete`` /
        ``produced_unverified`` / ``failed``.

        * ``complete`` — a user-supplied ``output_spec`` was fully validated.
        * ``produced_unverified`` — the file is structurally valid HDF5 (or no
          spec was given to validate against); physical correctness is NOT
          asserted.
        * ``failed`` — preflight, engine, or validation failure; the reason and
          return code (when an engine process ran) are recorded.
        """
        self._preflight(run)
        env = os.environ.copy()
        env.pop("DISPLAY", None)
        env["PGPLOT"] = "none"
        self._status(run, "running")
        try:
            proc = subprocess.run([*self.launcher, "run.mac"], cwd=run.directory,
                                  input="exit\n", text=True, capture_output=True,
                                  timeout=self.timeout_seconds, env=env, check=False)
        except (FileNotFoundError, subprocess.TimeoutExpired) as exc:
            self._status(run, "failed", reason=str(exc), engine_started=False)
            raise RuntimeError(f"DISCUS could not complete; see {run.directory}") from exc

        log = proc.stdout + "\n--- STDERR ---\n" + proc.stderr
        (run.directory / "run.log").write_text(log, encoding="utf-8")
        output = run.directory / "diffuse.h5"
        engine_error = _ENGINE_ERROR_PATTERN.search(log)

        if proc.returncode != 0 or engine_error:
            self._status(run, "failed", returncode=proc.returncode,
                        reason="Engine error in log, nonzero exit, or missing output",
                        engine_error=engine_error.group(0) if engine_error else None)
            raise RuntimeError(f"DISCUS run failed; inspect {run.directory / 'run.log'}")

        if not output.is_file() or output.stat().st_size == 0:
            self._status(run, "failed", returncode=proc.returncode,
                        reason="Engine exited 0 but did not produce a nonempty diffuse.h5")
            raise RuntimeError(f"DISCUS produced no output; inspect {run.directory / 'run.log'}")

        try:
            report = _validate_hdf5_output(output, output_spec)
        except (ValueError, OSError) as exc:
            self._status(run, "failed", returncode=proc.returncode,
                        reason=f"Output validation failed: {exc}")
            raise RuntimeError(f"Invalid 3D output; inspect {run.directory / 'run.log'}") from exc

        if output_spec is not None:
            self._status(run, "complete", returncode=proc.returncode,
                        output_validation=report)
        else:
            # Structurally valid HDF5, but no user-supplied spec was validated:
            # do not claim scientific completeness.
            self._status(run, "produced_unverified", returncode=proc.returncode,
                        output_validation=report,
                        reason="No output spec supplied; structural HDF5 check only")
        return run

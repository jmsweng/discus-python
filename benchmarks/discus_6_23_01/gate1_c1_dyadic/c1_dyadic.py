"""Pre-registered Gate 1 discriminating experiment: is the archived C1 `set aver,100` residual
(1.77 % relative L2) caused by DISCUS's integer phase table at a non-dyadic hkl step?

Background (read-only analysis, 2026-10-28; see ../REVIEW_2026-10-28.md):
  * With Waasmaier-Kirfel f evaluated at s rounded to 0.001 1/A (DISCUS four_formtab), the archived
    C1 TOTAL intensity is reproduced to 2.4e-6 relative L2, but the DIFFUSE residual stays 1.77 %.
  * At voxels where diffuse and model disagree by > 5 %, the engine's total amplitude agrees with the
    model to ~0.03 (units of F) while the diffuse amplitude differs by ~0.9: the error is in <F>.L,
    which nearly cancels F there (diffuse/total ~ 1e-5).
  * DISCUS turbo accumulates phases as NINT(2^22 * frac(step . x)) integers per grid step and looks up
    exp() in a 2^16 table. For step 0.01 the increments are inexact; for step 1/128 with the C1
    positions (multiples of 1/4) and lattice vectors (integers) every phase is exact (1/512 cycle).
Prediction: on a dyadic grid (corner -20/128, step 1/128, 41 points;
almost the same window as the archived +-0.16) the engine diffuse equals the
DISCUS-semantics oracle (per-site average cell x lattice interference function, celltoindex order;
engine-precision inputs: DISCUS's own W-K table, f at s rounded to 0.001)
to <= 1e-6 relative L2, and the total to <= 1e-9. If the diffuse residual stays at the percent level,
the phase-table hypothesis is refuted and the averaging model is still incomplete.
A second macro re-runs the archived 0.01-step macro unchanged; prediction: data_values identical
to the archived volumes (engine/binary reproducibility on this machine).

Usage:
  python c1_dyadic.py predict              # writes inputs/ and predictions.json (already done)
  python c1_dyadic.py analyze RUN_DIR      # after the engine run; writes c1_results.json/.md
"""
from __future__ import annotations

import hashlib
import json
import shutil
import sys
import tarfile
import tempfile
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
TARBALL = REPO / "structure_factor_benchmark_v4.2.tar.gz"
C1_SHA = "ceefca57e26ab40e03d2adfd443cff559bd7fc3c837402f418f6e8def35406b9"
ARCH_SHA = {"C1_offcomm_total.h5": "b7a36c50f64c0f1f92feea8e0bf1a49c8d7047defb638f6f2ce77c0f3c6fa4fe",
            "C1_offcomm_diffuse.h5": "d2c2e913ad6b7c123af3d0a8a3b68895bc7112fc180bef8c414bad4b11c25ce4"}
A_C1, B_ISO, NCAT, ICC = 5.6537, 1.0, 8, 8
DYADIC = {"corner": -20.0 / 128, "step": 1.0 / 128, "n": 41}   # window ~ archived +-0.16
ARCHIVED = {"corner": -0.16, "step": 0.01, "n": 33}
THRESH = {"dyadic_total_relL2_max": 1e-9, "dyadic_diffuse_relL2_max": 1e-6,
          "repro_max_abs_diff_over_max": 1e-12}   # OpenMP summation order may differ

MACRO = """# Gate 1 pre-registered C1 run on a dyadic hkl grid (generated by c1_dyadic.py; do not edit)
discus
read
  stru C1_frozen.stru
eval n[1]
eval n[3]
fourier
  xray
  wvle moa1
  ll {lo},{lo},{lo}
  lr {hi},{lo},{lo}
  ul {lo},{hi},{lo}
  tl {lo},{lo},{hi}
  na {n}
  no {n}
  nt {n}
  abs h
  ord k
  top l
  temp use
  disp off
  lots off
  set technique:turbo
  set aver,0.0
  show
  run
exit
output
  value int
  form nexus
  outf {tag}_total.h5
  run
exit
fourier
  set aver,100.0
  show
  run
exit
output
  value int
  form nexus
  outf {tag}_diffuse.h5
  run
exit
exit
exit
"""


def sha(p) -> str:
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def extract_archive(dst: Path) -> Path:
    with tarfile.open(TARBALL) as t:
        for m in t.getmembers():
            if m.name.endswith((".stru", ".h5", ".cl")):
                m.name = Path(m.name).name
                t.extract(m, dst, filter="data")
    return dst


def wk(el, s, source="dabax"):
    """W-K f(s); 'discus' = DISCUS 6.23.01's own table (engine inputs), 'dabax' = independent copy."""
    W = json.loads((HERE.parent / "gate2_prereg" / "wk_coefficients.json").read_text())["elements"][el][source]
    return W["c"] + sum(a * np.exp(-b * s * s) for a, b in zip(W["a"], W["b"]))


def load_c1(path: Path):
    if sha(path) != C1_SHA:
        raise SystemExit(f"C1 structure hash mismatch: {path}")
    sp, x = [], []
    for line in path.read_text().splitlines():
        t = line.replace(",", " ").split()
        if t and t[0] in ("GA", "AS"):
            sp.append(t[0]); x.append([float(v) for v in t[1:4]])
    sp, x = np.array(sp), np.array(x)
    ic = np.arange(len(sp)) // NCAT                       # DISCUS celltoindex, x fastest
    cell = np.stack([ic % ICC, (ic // ICC) % ICC, ic // ICC ** 2], 1) + np.rint(x.min(0))
    red = x - cell
    assert red.min() >= -1e-12 and red.max() < 1
    return sp, x, red, np.unique(cell, axis=0)


def forward(path: Path, grid: dict, mode: str = "engine"):
    """Total and DISCUS-`set aver,100` diffuse on the grid; axes (h,k,l); f at rounded s if engine."""
    sp, x, red, cells = load_c1(path)
    h = grid["corner"] + grid["step"] * np.arange(grid["n"])
    hkl = np.stack(np.meshgrid(h, h, h, indexing="ij"), -1).reshape(-1, 3)
    s = np.linalg.norm(hkl, axis=1) / (2 * A_C1)
    if mode == "engine":
        s = np.floor(s * (1.0 / 0.001) + 0.5) * 0.001
    F = np.zeros(len(hkl), complex); Fa = np.zeros(len(hkl), complex)
    for el in ("GA", "AS"):
        m = sp == el
        fe = wk(el, s, "discus" if mode == "engine" else "dabax") * np.exp(-B_ISO * s * s)
        for blk in range(0, m.sum(), 512):
            F += fe * np.exp(2j * np.pi * hkl @ x[m][blk:blk + 512].T).sum(1)
            Fa += fe * np.exp(2j * np.pi * hkl @ red[m][blk:blk + 512].T).sum(1)
    L = np.exp(2j * np.pi * hkl @ cells.T).sum(1)
    shape = (grid["n"],) * 3
    return (np.abs(F) ** 2).reshape(shape), (np.abs(F - Fa / len(cells) * L) ** 2).reshape(shape)


def rel(a, b):
    return float(np.linalg.norm(a - b) / np.linalg.norm(b))


def read_values(p: Path, grid: dict, bragg: str):
    import h5py
    with h5py.File(p) as f:
        d = f["entry/data"]
        v = d["data_values"][()]
        ok = (np.allclose(d["data_corner"][()], grid["corner"]) and
              np.allclose(d["data_increment_vector"][()], np.eye(3) * grid["step"]) and
              d["data_type_with_bragg"][()].decode() == bragg and v.shape == (grid["n"],) * 3)
    if not ok:
        raise SystemExit(f"{p.name}: grid/metadata differ from registration")
    return v


def predict():
    inp = HERE / "inputs"; inp.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory() as td:
        arch = extract_archive(Path(td))
        for k, v in ARCH_SHA.items():
            assert sha(arch / k) == v
        shutil.copy(arch / "C1_frozen.stru", inp / "C1_frozen.stru")
        It_a, Id_a = forward(inp / "C1_frozen.stru", ARCHIVED)
        e_t = rel(It_a, read_values(arch / "C1_offcomm_total.h5", ARCHIVED, "bragg_present"))
        e_d = rel(Id_a, read_values(arch / "C1_offcomm_diffuse.h5", ARCHIVED, "bragg_subtracted"))
        repro = (arch / "offcommensurate_macro.cl").read_text().replace("C1_offcomm_", "c1_repro_")
    lo, hi = DYADIC["corner"], DYADIC["corner"] + DYADIC["step"] * (DYADIC["n"] - 1)
    (inp / "c1_dyadic.mac").write_text(MACRO.format(lo=lo, hi=hi, n=DYADIC["n"], tag="c1_dyadic"))
    (inp / "c1_repro.mac").write_text("# Archived C1 macro, output names changed only (generated)\n" + repro)
    It, Id = forward(inp / "C1_frozen.stru", DYADIC)
    pred = {"schema": "gate1-c1-dyadic-v1", "status": "PRE-REGISTERED before any engine run",
            "grid_dyadic": DYADIC, "grid_archived": ARCHIVED, "thresholds": THRESH,
            "archived_residual_engine_precision_oracle": {"total_relL2": e_t, "diffuse_relL2": e_d},
            "dyadic_oracle_sha256": {"total": hashlib.sha256(It.tobytes()).hexdigest(),
                                     "diffuse": hashlib.sha256(Id.tobytes()).hexdigest()},
            "inputs_sha256": {p.name: sha(p) for p in sorted(inp.iterdir())},
            "code_sha256": {"c1_dyadic.py": sha(__file__),
                            "wk_coefficients.json": sha(HERE.parent / "gate2_prereg" / "wk_coefficients.json")}}
    (HERE / "predictions.json").write_text(json.dumps(pred, indent=1, sort_keys=True) + "\n")
    print(json.dumps(pred["archived_residual_engine_precision_oracle"]))


def analyze(run: Path):
    pred = json.loads((HERE / "predictions.json").read_text())
    probs = [f"changed: {k}" for k, v in pred["code_sha256"].items()
             if sha(HERE / k if k == "c1_dyadic.py" else HERE.parent / "gate2_prereg" / k) != v]
    probs += [f"run-dir input differs/missing: {k}" for k, v in pred["inputs_sha256"].items()
              if not (run / k).exists() or sha(run / k) != v]
    res = {"status": None, "problems": probs, "criteria": []}
    if not probs:
        It, Id = forward(run / "C1_frozen.stru", DYADIC)
        Et = read_values(run / "c1_dyadic_total.h5", DYADIC, "bragg_present")
        Ed = read_values(run / "c1_dyadic_diffuse.h5", DYADIC, "bragg_subtracted")
        c = [("dyadic total vs oracle relL2", rel(Et, It), THRESH["dyadic_total_relL2_max"]),
             ("dyadic diffuse vs oracle relL2", rel(Ed, Id), THRESH["dyadic_diffuse_relL2_max"])]
        with tempfile.TemporaryDirectory() as td:
            arch = extract_archive(Path(td))
            for kind, bragg in (("total", "bragg_present"), ("diffuse", "bragg_subtracted")):
                A = read_values(arch / f"C1_offcomm_{kind}.h5", ARCHIVED, bragg)
                R = read_values(run / f"c1_repro_{kind}.h5", ARCHIVED, bragg)
                c.append((f"archived macro rerun, {kind}: max|diff|/max", float(np.max(np.abs(R - A)) / A.max()),
                          THRESH["repro_max_abs_diff_over_max"]))
        res["criteria"] = [{"criterion": n, "value": v, "limit": l, "pass": bool(v <= l)} for n, v, l in c]
        res["status"] = "PASS" if all(x["pass"] for x in res["criteria"]) else "FAIL"
    else:
        res["status"] = "INVALID"
    (run / "c1_results.json").write_text(json.dumps(res, indent=1) + "\n")
    lines = [f"# Gate 1 C1 dyadic experiment: {res['status']}", ""] + [f"- INVALID: {p}" for p in probs]
    lines += [f"- {x['criterion']}: {x['value']:.3e} (limit {x['limit']:.1e}) {'PASS' if x['pass'] else 'FAIL'}"
              for x in res["criteria"]]
    (run / "C1_RESULTS_PREREG.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    sys.exit({"PASS": 0, "FAIL": 1}.get(res["status"], 2))


if __name__ == "__main__":
    if sys.argv[1:2] == ["predict"]:
        predict()
    elif sys.argv[1:2] == ["analyze"] and len(sys.argv) == 3:
        analyze(Path(sys.argv[2]))
    else:
        print(__doc__); sys.exit(2)

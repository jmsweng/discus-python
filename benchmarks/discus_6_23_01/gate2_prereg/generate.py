"""Generate the pre-registered Gate 2 inputs and predictions (run BEFORE any engine run).

Writes, next to this file:
  inputs/gate2_{block,random}.stru          frozen structures (DISCUS layout, ncell 16,16,16,1)
  inputs/gate2_{block,random}_{total,diffuse}.mac, inputs/gate2_probe.mac
  predictions.json                          all predicted numbers, thresholds and input hashes

Deterministic: running it again must reproduce byte-identical files (checked by analyze.py and tests).
The predictions use only oracle.py (numpy) plus, for the pipeline self-consistency entry, the package
under test applied to ORACLE data (never to engine data).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import oracle as O  # noqa: E402

INPUTS = HERE / "inputs"
MACRO = """# Gate 2 pre-registered run: {model} model, set aver,{aver}  (generated by generate.py; do not edit)
discus
read
  stru {stru}
eval n[1]
eval n[2]
eval n[3]
fourier
  xray
  wvle moa1
  ll -4.0,-4.0,-4.0
  lr  3.9375,-4.0,-4.0
  ul -4.0, 3.9375,-4.0
  tl -4.0,-4.0, 3.9375
  na 128
  no 128
  nt 128
  abs h
  ord k
  top l
  temp use
  disp off
  lots off
  set technique:turbo
  set aver,{aver}
  show
  run
exit
output
  value int
  form nexus
  outf {out}
  run
exit
exit
exit
"""
PROBE = """# Gate 2 probe: confirm DISCUS reads the structure as 16x16x16 cells x 1 atom (generated; do not edit)
discus
read
  stru gate2_block.stru
eval n[1]
eval n[2]
eval n[3]
exit
exit
"""

THRESHOLDS = {
    "C0_total_vs_engine_precision_relL2_max": 1e-6,
    "C0_total_vs_physics_relL2_factor_of_eps_tab": 3.0,
    "C1_diffuse_at_integer_H_max_over_max_diffuse": 1e-9,
    "C1_diffuse_minus_total_off_integer_relL2_max": 1e-9,
    "A_corr_recovery_physics_max_abs_err_over_N": 1e-3,
    "A_corr_recovery_engine_precision_max_abs_err_over_N": 1e-6,
    "B1_dpdf_vs_oracle_physics_relL2_factor_of_eps_tab": 3.0,
    "B1_dpdf_vs_oracle_engine_precision_relL2_max": 1e-6,
    "B2_ratio_abs_tolerance": 0.01,
    "B2_sign_required_if_abs_predicted_ratio_ge": 0.05,
    "B3_imag_over_real_max": 1e-10,
    "B3_friedel_rel_error_max": 1e-12,
    "N_control_abs_nn_ratio_max": 0.05,
    "floor_for_factor_thresholds": 1e-6,
}


def tkey(t):
    return ",".join(str(int(v)) for v in t)


def main():
    INPUTS.mkdir(exist_ok=True)
    files = {}
    for model in ("block", "random"):
        sig = O.build_sigma(model)
        stru = INPUTS / f"gate2_{model}.stru"
        stru.write_text(O.stru_text(sig, f"gate2_{model}_seed{O.SEEDS[model]}"))
        assert np.array_equal(O.parse_stru(stru), sig)
        files[stru.name] = stru
        for kind, aver in (("total", "0.0"), ("diffuse", "100.0")):
            mac = INPUTS / f"gate2_{model}_{kind}.mac"
            mac.write_text(MACRO.format(model=model, aver=aver, stru=stru.name,
                                        out=f"gate2_{model}_{kind}.h5"))
            files[mac.name] = mac
    probe = INPUTS / "gate2_probe.mac"; probe.write_text(PROBE); files[probe.name] = probe

    sys.path.insert(0, str(HERE.parents[2] / "src"))
    from discuspdf.discus_output import DiscusVolume, delta_pdf_fractional

    def pipeline(I, bragg="bragg_subtracted"):
        vol = DiscusVolume(I, np.full(3, -O.H_MAX), np.eye(3) * O.DH, np.full(3, O.A_CELL),
                           np.full(3, 90.0), bragg)
        r = delta_pdf_fractional(vol, imaginary_tolerance=1e-6)
        return r

    pred = {"schema": "gate2-prereg-v2",
            "status": "PRE-REGISTERED: written before any engine run of these inputs that produced data",
            "deviation_from_v1": (
                "v1 (commit c3ab156) atom lines had two blanks after the 4-character name, shifting every "
                "fixed-column field by one; DISCUS 6.23.01 rejected the file at 'read stru' (error -49, "
                "'File format specified as numbers only'), so the probe reported n[1]=0 and no data macro "
                "was run (evidence/20261028T232749Z_LAPTOP-NGU3BT0N). v2 writes DISCUS's own FORMAT 4 "
                "layout, checked by an emulation of read_atom_line against the DISCUS-written C1 file. "
                "Design, seeds, grid, oracle physics, predictions and thresholds are unchanged."),
            "design": {"lattice": "simple cubic", "a_A": O.A_CELL, "cells": [O.N_CELL] * 3,
                       "atoms_per_cell": 1, "species": {"-1": "CU", "+1": "AU"}, "B_iso": 0.0,
                       "H_axis": {"first": float(O.H_AXIS[0]), "step": O.DH, "n": O.N_H,
                                  "last": float(O.H_AXIS[-1])},
                       "real_space_step_cells": 1.0 / (O.N_H * O.DH),
                       "boundary": "commensurate sampling: finite-crystal sum == periodic sum exactly",
                       "form_factors": "Waasmaier-Kirfel 1995 (DABAX transcription), f0 only, no anomalous",
                       "engine_precision_model": "f at s rounded to 0.001 1/A with Fortran NINT",
                       "seeds": O.SEEDS, "tau_points": [tkey(t) for t in O.TAU_POINTS]},
            "thresholds": THRESHOLDS, "models": {}}
    for model in ("block", "random"):
        sig = O.build_sigma(model)
        C = O.pair_sums_direct(sig)
        Cfft = np.rint(np.real(np.fft.ifftn(np.abs(np.fft.fftn(sig)) ** 2))).astype(np.int64)
        assert np.array_equal(C, Cfft), "direct and FFT pair sums disagree"
        Nn = sig.size
        out = {"n_AU": int((sig > 0).sum()), "n_CU": int((sig < 0).sum()),
               "C_over_N_realized": {tkey(t): C[tuple(np.mod(t, O.N_CELL))] / Nn for t in O.TAU_POINTS},
               "C_sha256": O.sha256_array(C)}
        ens = O.ensemble_sd(model)
        out["ensemble_MC_mean_sd"] = {tkey(t): list(v) for t, v in ens.items()}
        if model in O.ENSEMBLE:
            out["ensemble_analytic"] = {tkey(t): v for t, v in O.ENSEMBLE[model].items()}
        out["realized_z_vs_ensemble"] = {tkey(t): (out["C_over_N_realized"][tkey(t)] - ens[t][0]) / ens[t][1]
                                         for t in O.TAU_POINTS if ens[t][1] > 0}
        res = {}
        for mode in ("physics", "engine"):
            It, Id, g2 = O.forward(sig, mode)
            K = O.kernel_on_lattice(g2)
            rho = O.predicted_rho(C, K)
            r = pipeline(Id)
            c0 = O.N_H // 2                       # u = 0 after fftshift (n even)
            st = O.N_H // O.N_CELL                # grid points per lattice vector (u step 1/8 cell)
            assert np.isclose(r.u_axes[0][c0], 0.0) and np.isclose(r.u_axes[0][c0 + st], 1.0)
            rho_pipe = {tkey(t): float(r.real_volume[c0 + t[0] * st, c0 + t[1] * st, c0 + t[2] * st])
                        for t in O.TAU_POINTS}
            res[mode] = dict(It=It, Id=Id, g2=g2, K=K, rho=rho, rho_pipe=rho_pipe, r=r)
            out[f"{mode}"] = {
                "I_total_sha256": O.sha256_array(It), "I_diffuse_sha256": O.sha256_array(Id),
                "I_total_fingerprint": O.fingerprint(It), "I_diffuse_fingerprint": O.fingerprint(Id),
                "max_I_total": float(It.max()), "max_I_diffuse": float(Id.max()),
                "kernel_K1_over_K0": float(K[1, 0, 0] / K[0, 0, 0]),
                "rho_pred": {tkey(t): v for t, v in rho.items()},
                "rho_pred_ratio": {tkey(t): v / rho[(0, 0, 0)] for t, v in rho.items()},
                "pipeline_on_oracle_vs_independent_rho_max_abs_over_rho0": float(max(
                    abs(rho_pipe[tkey(t)] - rho[t]) for t in O.TAU_POINTS) / rho[(0, 0, 0)]),
                "pipeline_on_oracle_imag_over_real": r.imaginary_ratio,
                "pipeline_on_oracle_friedel": r.friedel_relative_error,
            }
        P, E = res["physics"], res["engine"]
        out["eps_tab"] = {"I_total_relL2": O.rel_l2(E["It"], P["It"]),
                          "I_diffuse_relL2": O.rel_l2(E["Id"], P["Id"]),
                          "dpdf_relL2": O.rel_l2(E["r"].real_volume, P["r"].real_volume)}
        pred["models"][model] = out
    pred["input_sha256"] = {name: O.sha256_file(p) for name, p in sorted(files.items())}
    pred["code_sha256"] = {n: O.sha256_file(HERE / n) for n in
                           ("oracle.py", "generate.py", "analyze.py", "selftest.py",
                            "compare_form_factors.py", "wk_coefficients.json")}
    (HERE / "predictions.json").write_text(json.dumps(pred, indent=1, sort_keys=True) + "\n")
    for model, m in pred["models"].items():
        print(model, "eps_tab", m["eps_tab"])
        print("  ratios physics:", {k: round(v, 4) for k, v in m["physics"]["rho_pred_ratio"].items()})
        print("  realized C/N  :", {k: round(v, 4) for k, v in m["C_over_N_realized"].items()})
        print("  z vs ensemble :", {k: round(v, 2) for k, v in m["realized_z_vs_ensemble"].items()})
        print("  pipeline-vs-independent:", m["physics"]["pipeline_on_oracle_vs_independent_rho_max_abs_over_rho0"],
              "K1/K0", m["physics"]["kernel_K1_over_K0"])


if __name__ == "__main__":
    main()

"""Generate the Package D MMC engine probe (DISCUS_SUITE 6.23.01).

Run from the repository root:  python benchmarks/discus_6_23_01/d_mc_probes/make_inputs.py
Writes inputs/*.stru, inputs/*.mac, inputs/runs.txt and runs.json. Committed before the engine run; predictions
are in PREDICTIONS.md. The probes record what DISCUS's MMC does; they are not tests of our code.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from discuspdf.discus_io import format_stru
from discuspdf.lattice import Lattice
from discuspdf.structure import Structure
from discuspdf.structure_ops import repeat

HERE = Path(__file__).resolve().parent
INPUTS = HERE / "inputs"
SEED = "seed 11,22,33,44,55,66,77,88"
A = 3.0


def sc(n, species="Cu"):
    cell = Structure(Lattice.from_parameters(A, A, A, 90, 90, 90), [species], [[0, 0, 0]],
                     model="configuration", site_label=["s1"], b_iso=[0.5])
    return repeat(cell, (n, n, n)).structure


def cuau(n=16):
    st = sc(n)
    rng = np.random.default_rng(20261102)
    sp = np.array(st.species, dtype=object)
    sp[rng.permutation(st.n_atoms)[: st.n_atoms // 2]] = "Au"
    return st.replace(species=sp, b_iso=np.full(st.n_atoms, 0.5))


def cu_disp(n=12):
    st = sc(n)
    rng = np.random.default_rng(20261103)
    return st.with_cartesian(st.cartesian + rng.normal(0.0, 0.05, (st.n_atoms, 3)))


SIX_VECTORS = ["set vec, 1, 1, 1, 1, 0, 0", "set vec, 2, 1, 1, -1, 0, 0", "set vec, 3, 1, 1, 0, 1, 0",
               "set vec, 4, 1, 1, 0, -1, 0", "set vec, 5, 1, 1, 0, 0, 1", "set vec, 6, 1, 1, 0, 0, -1",
               "set neig, rese", "set neig, vec, 1, 2, 3, 4, 5, 6, number:1"]


def macro(name, stru, mmc_lines, *, serial=True, save=True):
    lines = [f"# D MMC probe {name} (generated by make_inputs.py; do not edit)", "discus", SEED]
    if serial:
        lines.append("set parallel, useomp:off")
    lines += ["read", f"  stru {stru}", "mmc"] + mmc_lines + ["show", "run", "exit"]
    if save:
        lines.append(f"save {name}_out.stru")
    lines += ["exit", "exit", ""]
    return "\n".join(lines)


def occ(target_line, temp="1.0", cyc=40960, feed=4096):
    return SIX_VECTORS + ["set mode, 1.0, swchem, all", target_line, f"set temp, {temp}",
                          f"set cyc, {cyc}", f"set feed, {feed}"]


def disp(target_lines, mode="shift", move=True, cyc=17280, feed=1728):
    lines = list(SIX_VECTORS) + [f"set mode, 1.0, {mode}, all"]
    if move:
        lines.append("set move, Cu, 0.01, 0.01, 0.01")
    return lines + target_lines + ["set temp, 1.0", f"set cyc, {cyc}", f"set feed, {feed}"]


RUNS = [
    # name, structure, mmc lines, OMP_NUM_THREADS ("" = unset), serial
    ("r1_occ_corr", "cuau.stru", occ("set target, 1, corr, Cu, Au, -0.3, 0.0, CORR"), "", True),
    ("r1b_occ_corr_repeat", "cuau.stru", occ("set target, 1, corr, Cu, Au, -0.3, 0.0, CORR"), "", True),
    ("r1c_occ_corr_omp4", "cuau.stru", occ("set target, 1, corr, Cu, Au, -0.3, 0.0, CORR"), "4", False),
    ("r1d_occ_corr_omp4_repeat", "cuau.stru", occ("set target, 1, corr, Cu, Au, -0.3, 0.0, CORR"), "4", False),
    ("r2_occ_ener_zero", "cuau.stru", occ("set target, 1, corr, Cu, Au, 0.0, 0.0, ENER", cyc=20000, feed=20000), "", True),
    ("r3_occ_ener_hot", "cuau.stru", occ("set target, 1, corr, Cu, Au, 0.0, 1.0, ENER", temp="10000.0", cyc=20000,
                                         feed=20000), "", True),
    ("r3b_occ_ener_cold", "cuau.stru", occ("set target, 1, corr, Cu, Au, 0.0, 0.5, ENER", cyc=40960), "", True),
    ("r4_shift_spring", "cu_disp.stru", disp(["set target, 1, spring, Cu, Cu, 3.0, 1.0"]), "", True),
    ("r4b_shift_no_move", "cu_disp.stru", disp(["set target, 1, spring, Cu, Cu, 3.0, 1.0"], move=False), "", True),
    ("r5_shift_lennard", "cu_disp.stru", disp(["set target, 1, lennard, Cu, Cu, 3.0, 1.0, 12, 6"]), "", True),
    ("r6_swdisp_cd", "cu_disp.stru",
     disp(["set target, 1, cd, Cu, Cu, 0.3, 0.0, CORR, dir:[1,0,0]"], mode="swdisp", move=False), "", True),
]


def main() -> None:
    INPUTS.mkdir(exist_ok=True)
    (INPUTS / "cuau.stru").write_text(format_stru(cuau(), title="D MMC probe Cu0.5Au0.5 sc 16^3"), newline="\n")
    (INPUTS / "cu_disp.stru").write_text(format_stru(cu_disp(), title="D MMC probe Cu sc 12^3 displaced"),
                                         newline="\n")
    rows, meta = [], []
    for name, stru, lines, omp, serial in RUNS:
        (INPUTS / f"{name}.mac").write_text(macro(name, stru, lines, serial=serial), newline="\n")
        rows.append(f"{name} {omp or '-'}")
        meta.append({"id": name, "structure": stru, "omp_num_threads": omp or None, "serial": serial})
    (INPUTS / "runs.txt").write_text("\n".join(rows) + "\n", newline="\n")
    (HERE / "runs.json").write_text(json.dumps({"runs": meta}, indent=1) + "\n", newline="\n")


if __name__ == "__main__":
    main()

"""Generate the Package D reference-scattering probe (DISCUS_SUITE 6.23.01 vs discuspdf.reference_scattering).

Run from the repository root:  python benchmarks/discus_6_23_01/d_reference/make_inputs.py
Writes inputs/*.stru, inputs/*.mac and runs.json. The generated files are committed before the engine run
and must not be edited by hand; PREREG.md fixes the comparison criteria in advance.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from discuspdf.discus_io import format_stru
from discuspdf.lattice import Lattice
from discuspdf.structure import Structure
from discuspdf.structure_ops import repeat

HERE = Path(__file__).resolve().parent
INPUTS = HERE / "inputs"

B_ISO = {"Cu": 0.5, "Au": 0.8, "Ga": 0.6, "As": 0.6}


def cuau() -> Structure:
    """fcc Cu0.75Au0.25 (a = 3.75 Å), 4×4×4 cells, random occupation (seed 20261101)."""
    lat = Lattice.from_parameters(3.75, 3.75, 3.75, 90, 90, 90)
    cell = Structure(lat, ["Cu"] * 4, [[0, 0, 0], [.5, .5, 0], [.5, 0, .5], [0, .5, .5]],
                     model="configuration", site_label=["s1", "s2", "s3", "s4"])
    st = repeat(cell, (4, 4, 4)).structure
    rng = np.random.default_rng(20261101)
    au = rng.permutation(st.n_atoms)[: st.n_atoms // 4]
    species = np.array(st.species, dtype=object)
    species[au] = "Au"
    return st.replace(species=species, b_iso=np.array([B_ISO[s] for s in species]))


def gaas_mono() -> Structure:
    """Monoclinic two-site cell (a 4.1, b 5.3, c 3.7 Å, β 103°), 3×3×3, Gaussian displacements σ = 0.05 Å."""
    lat = Lattice.from_parameters(4.1, 5.3, 3.7, 90, 103, 90)
    cell = Structure(lat, ["Ga", "As"], [[0.05, 0.1, 0.2], [0.55, 0.62, 0.71]], model="configuration",
                     site_label=["s1", "s2"])
    st = repeat(cell, (3, 3, 3)).structure
    rng = np.random.default_rng(1103)
    cart = st.cartesian + rng.normal(0.0, 0.05, (st.n_atoms, 3))
    st = st.with_cartesian(cart)
    return st.replace(b_iso=np.array([B_ISO[s] for s in st.species]))


def grid_lines(ll, lr, ul, tl, n):
    f = lambda v: ",".join(f"{x:.6g}" for x in v)   # noqa: E731
    return [f"  ll {f(ll)}", f"  lr {f(lr)}", f"  ul {f(ul)}", f"  tl {f(tl)}",
            f"  na {n[0]}", f"  no {n[1]}", f"  nt {n[2]}"]


GRIDS = {
    # commensurate with 4 cells: step 0.25
    "c4": dict(ll=(-2, -2, 0), lr=(2, -2, 0), ul=(-2, 2, 0), tl=(-2, -2, 2), n=(17, 17, 9)),
    # NOT commensurate with 4 cells: step 0.3
    "nc": dict(ll=(-1.5, -1.5, 0.3), lr=(1.5, -1.5, 0.3), ul=(-1.5, 1.5, 0.3), tl=(-1.5, -1.5, 1.8), n=(11, 11, 6)),
    # general region for the monoclinic, displaced structure: step 0.2
    "m": dict(ll=(-2, -1, 0.5), lr=(2, -1, 0.5), ul=(-2, 3, 0.5), tl=(-2, -1, 2.5), n=(21, 21, 11)),
}


def macro(run_id, stru, radiation, grid, aver):
    g = GRIDS[grid]
    lines = [f"# D reference probe {run_id} (generated by make_inputs.py; do not edit)", "discus",
             "read", f"  stru {stru}", "fourier", f"  {radiation}", "  wvle moa1"]
    lines += grid_lines(g["ll"], g["lr"], g["ul"], g["tl"], g["n"])
    lines += ["  abs h", "  ord k", "  top l", "  temp use", "  disp off", "  lots off",
              "  set technique:turbo", f"  set aver,{aver:.1f}", "  show", "  run", "exit",
              "output", "  value int", "  form nexus", f"  outf {run_id}.h5", "  run", "exit",
              "exit", "exit", ""]
    return "\n".join(lines)


RUNS = [
    # id,            structure,       radiation, grid, aver
    ("cuau_x_tot_c4", "cuau.stru", "xray", "c4", 0.0),
    ("cuau_x_dif_c4", "cuau.stru", "xray", "c4", 100.0),
    ("cuau_n_tot_c4", "cuau.stru", "neut", "c4", 0.0),
    ("cuau_n_dif_c4", "cuau.stru", "neut", "c4", 100.0),
    ("cuau_x_tot_nc", "cuau.stru", "xray", "nc", 0.0),
    ("cuau_x_dif_nc", "cuau.stru", "xray", "nc", 100.0),
    ("mono_x_tot_m", "mono.stru", "xray", "m", 0.0),
    ("mono_n_tot_m", "mono.stru", "neut", "m", 0.0),
]


def main() -> None:
    INPUTS.mkdir(exist_ok=True)
    (INPUTS / "cuau.stru").write_text(format_stru(cuau(), title="D reference CuAu fcc 4x4x4"), newline="\n")
    (INPUTS / "mono.stru").write_text(format_stru(gaas_mono(), title="D reference monoclinic GaAs 3x3x3"),
                                      newline="\n")
    runs = []
    for run_id, stru, rad, grid, aver in RUNS:
        (INPUTS / f"{run_id}.mac").write_text(macro(run_id, stru, rad, grid, aver), newline="\n")
        runs.append({"id": run_id, "structure": stru, "radiation": rad, "grid": grid, "aver": aver,
                     "output": f"{run_id}.h5"})
    (HERE / "runs.json").write_text(json.dumps({"runs": runs, "grids": GRIDS, "b_iso": B_ISO}, indent=1) + "\n",
                                    newline="\n")


if __name__ == "__main__":
    main()

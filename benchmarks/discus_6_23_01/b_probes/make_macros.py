"""Generate the Package B engine-probe macros and runs.json (DISCUS_SUITE 6.23.01).

Run from the repository root:  python benchmarks/discus_6_23_01/b_probes/make_macros.py
The generated files are committed; do not edit them by hand. Each probe answers one question
listed in README.md. Nothing here is a pass/fail test of the engine: the probes record behaviour.
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
MACROS = HERE / "macros"

INPUTS = {
    "random": "benchmarks/discus_6_23_01/gate2_prereg/inputs/gate2_random.stru",
    "block": "benchmarks/discus_6_23_01/gate2_prereg/inputs/gate2_block.stru",
    "gaas": "tests/fixtures/discus_6_23_01/gaas.cll",
}
SEED8_A = "seed 11,22,33,44,55,66,77,88"
SEED8_B = "seed 81,72,63,54,45,36,27,18"
SEED1 = "seed 1234"


def grid(lo, step, n, plane=None):
    """Cubic hkl grid lo..lo+(n-1)*step on every axis."""
    hi = lo + (n - 1) * step
    return {"ll": (lo, lo, lo), "lr": (hi, lo, lo), "ul": (lo, hi, lo), "tl": (lo, lo, hi),
            "n": (n, n, n)}


G32 = grid(-2.0, 0.125, 32)     # commensurate with 16 cells (0.125*16 = 2), even: no Friedel merge
G33 = grid(-2.0, 0.125, 33)     # commensurate, odd and symmetric about 0
GNC = grid(-2.0, 0.2, 22)       # NOT commensurate with 16 cells (0.2*16 = 3.2)


def fmt(v):
    return ",".join(f"{x:.6g}" for x in v)


def macro(run_id, note, read, g, *, aver=0.0, lots="off", technique="turbo", seed=None,
          extra_set=(), values=("int",)):
    lines = [f"# B probe {run_id}: {note} (generated by make_macros.py; do not edit)", "discus"]
    if seed:
        lines.append(seed)
    lines += ["read", f"  {read}", "eval n[1]", "eval n[2]", "eval n[3]", "fourier", "  xray", "  wvle moa1",
              f"  ll {fmt(g['ll'])}", f"  lr {fmt(g['lr'])}", f"  ul {fmt(g['ul'])}", f"  tl {fmt(g['tl'])}",
              f"  na {g['n'][0]}", f"  no {g['n'][1]}", f"  nt {g['n'][2]}",
              "  abs h", "  ord k", "  top l", "  temp ignore", "  disp off", f"  lots {lots}",
              f"  set technique:{technique}", f"  set aver,{aver:.1f}"]
    lines += [f"  {s}" for s in extra_set]
    lines += ["  show", "  run", "exit", "output"]
    outputs = []
    for v in values:
        name = f"{run_id}_{v}.h5"
        outputs.append(name)
        lines += [f"  value {v}", "  form nexus", f"  outf {name}", "  run"]
    lines += ["exit", "exit", "exit", ""]
    return "\n".join(lines), outputs


def runs():
    R = []

    def add(run_id, note, struct, read, g, expect="ok", **kw):
        text, outputs = macro(run_id, note, read, g, **kw)
        R.append({"id": run_id, "group": run_id.split("_")[0], "note": note, "inputs": [INPUTS[struct]],
                  "outputs": outputs, "expect": expect, "text": text})

    gaas = "cell gaas.cll,4,4,4"
    # P1 planes and lines: what DISCUS writes for a 1-point axis.
    add("p1a_hk0", "hk0 plane, nt=1, tl=ll", "gaas", gaas,
        {"ll": (-2, -2, 0), "lr": (2, -2, 0), "ul": (-2, 2, 0), "tl": (-2, -2, 0), "n": (41, 41, 1)})
    add("p1b_h00", "h00 line, no=nt=1", "gaas", gaas,
        {"ll": (-2, 0, 0), "lr": (2, 0, 0), "ul": (-2, 0, 0), "tl": (-2, 0, 0), "n": (41, 1, 1)})
    add("p1c_hhl", "oblique hhl plane, nt=1", "gaas", gaas,
        {"ll": (-2, -2, -2), "lr": (2, 2, -2), "ul": (-2, -2, 2), "tl": (-2, -2, -2), "n": (41, 41, 1)})
    add("p1d_tloff", "hk0 plane, nt=1 but tl != ll", "gaas", gaas,
        {"ll": (-2, -2, 0), "lr": (2, -2, 0), "ul": (-2, 2, 0), "tl": (-2, -2, 1), "n": (41, 41, 1)},
        expect="either")
    add("p1e_h0l", "h0l plane, middle axis inactive (no=1)", "gaas", gaas,
        {"ll": (-2, 0, -2), "lr": (2, 0, -2), "ul": (-2, 0, -2), "tl": (-2, 0, 2), "n": (41, 1, 41)})

    # P2 set aver: amplitude vs intensity, partial averaging, seed reproducibility.
    rnd = "stru gate2_random.stru"
    three = ("int", "real", "imag")
    add("p2_aver0", "set aver 0", "random", rnd, G32, aver=0.0, values=three)
    add("p2_aver100", "set aver 100", "random", rnd, G32, aver=100.0, values=three)
    add("p2_aver50_s8a", "set aver 50, 8-value seed A", "random", rnd, G32, aver=50.0, seed=SEED8_A, values=three)
    add("p2_aver50_s8b", "set aver 50, 8-value seed A again", "random", rnd, G32, aver=50.0, seed=SEED8_A,
        values=three)
    add("p2_aver50_s8c", "set aver 50, 8-value seed B", "random", rnd, G32, aver=50.0, seed=SEED8_B, values=three)
    add("p2_aver50_s1a", "set aver 50, single-value seed", "random", rnd, G32, aver=50.0, seed=SEED1)
    add("p2_aver50_s1b", "set aver 50, single-value seed again", "random", rnd, G32, aver=50.0, seed=SEED1)

    # P3 lots: normalisation, periodicity, shape, seeds, combination with aver, limits.
    blk = "stru gate2_block.stru"
    add("p3_off", "lots off (reference)", "block", blk, G32)
    add("p3_box4_all_y", "lots box 4x4x4, all, periodic", "block", blk, G32, lots="box,4,4,4,all,y")
    add("p3_box4_all_n", "lots box 4x4x4, all, not periodic", "block", blk, G32, lots="box,4,4,4,all,n")
    add("p3_box4_n64_s8a", "lots box 4x4x4, 64 random lots, seed A", "block", blk, G32,
        lots="box,4,4,4,64,y", seed=SEED8_A)
    add("p3_box4_n64_s8b", "lots box 4x4x4, 64 random lots, seed A again", "block", blk, G32,
        lots="box,4,4,4,64,y", seed=SEED8_A)
    add("p3_box4_n64_s8c", "lots box 4x4x4, 64 random lots, seed B", "block", blk, G32,
        lots="box,4,4,4,64,y", seed=SEED8_B)
    add("p3_ell4_all_y", "lots ellipsoid 4x4x4, all, periodic", "block", blk, G32, lots="ell,4,4,4,all,y")
    add("p3_box4_all_y_aver100", "lots box 4x4x4, all, periodic, set aver 100", "block", blk, G32,
        lots="box,4,4,4,all,y", aver=100.0)
    add("p3_box16_n2_y", "lots box 16x16x16 (whole crystal), 2 lots, periodic", "block", blk, G32,
        lots="box,16,16,16,2,y", seed=SEED8_A)
    add("p3_box4_amp", "lots box 4x4x4, 8 lots, output value amp", "block", blk, G32,
        lots="box,4,4,4,8,y", seed=SEED8_A, values=("amp",), expect="either")
    add("p3_box17_err", "lots box 17x17x17 (larger than crystal)", "block", blk, G32,
        lots="box,17,17,17,8,y", expect="error")

    # P4 technique: turbo vs nufft on commensurate and non-commensurate grids.
    for gname, g in (("g32", G32), ("gnc", GNC)):
        for aver in (0.0, 100.0):
            for tech in ("turbo", "nufft"):
                add(f"p4_{tech}_{gname}_a{int(aver)}", f"technique {tech}, grid {gname}, aver {aver:g}",
                    "block", blk, g, aver=aver, technique=tech)

    # P5 Friedel/symmetry options on an odd, centred grid.
    add("p5_default", "odd grid, set aver 100, default symm", "block", blk, G33, aver=100.0)
    for opt in ("ignore", "friedel", "apply"):
        add(f"p5_symm_{opt}", f"odd grid, set aver 100, set symm:{opt}", "block", blk, G33, aver=100.0,
            extra_set=(f"set symm:{opt}",))
    return R


def main():
    MACROS.mkdir(exist_ok=True)
    for old in MACROS.glob("*.mac"):
        old.unlink()
    table = []
    for r in runs():
        for path in r["inputs"]:
            if not (REPO / path).is_file():
                raise SystemExit(f"missing input {path}")
        (MACROS / f"{r['id']}.mac").write_text(r.pop("text"), encoding="utf-8", newline="\n")
        r["macro"] = f"macros/{r['id']}.mac"
        table.append(r)
    (HERE / "runs.json").write_text(json.dumps({"discus_version": "6.23.01", "runs": table}, indent=1) + "\n",
                                    encoding="utf-8", newline="\n")
    print(f"{len(table)} runs written")


if __name__ == "__main__":
    main()

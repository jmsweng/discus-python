"""Generate the pre-registered Gate 0 v2 inputs and predictions (run BEFORE any engine run).

Writes, next to this file:
  inputs/gate0_{A,B}_{0..63}.stru          64 realizations per arm
  inputs/gate0_{A,B}_{total,diffuse}.mac   macros for both arms
  predictions.json                         seeds, thresholds, Gamma quantiles, SHA-256 hashes

Deterministic: running it again must reproduce byte-identical files.
The predictions use only oracle.py (numpy) plus, for the pipeline self-consistency entry, the package
under test applied to ORACLE data (never to engine data).
"""
from __future__ import annotations

import json
import secrets
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import oracle as O  # noqa: E402

INPUTS = HERE / "inputs"
K = 64  # number of realizations

# Macro template (copy the exact fourier command style from Gate 1/2)
MACRO = """# Gate 0 v2 pre-registered run: {arm} arm, {kind} (generated by gate0_generate.py; do not edit)
discus
read
  stru {stru}
eval n[1]
eval n[2]
eval n[3]
fourier
  xray
  wvle moa1
  ll 0.0,0.0,0.0
  lr  3.0,0.0,0.0
  ul 0.0, 3.0,0.0
  tl 0.0,0.0, 3.0
  na 25
  no 25
  nt 25
  abs h
  ord k
  top l
  {temp}
  disp off
  lots off
  set technique:turbo
  set aver,{aver}
  show
  run
exit
output
  value int
  form nexus
  outf {out}
  run
exit
exit
exit
"""


def build_average_structure():
    """Build the average structure: fcc, a=3.75, 4 sites, Cu p=0.75, Au p=0.25."""
    sys.path.insert(0, str(HERE.parents[2] / "src"))
    from discuspdf.lattice import Lattice
    from discuspdf.structure import Structure

    lat = Lattice.from_parameters(3.75, 3.75, 3.75, 90.0, 90.0, 90.0)
    # 4 sites: Cu and Au at each FCC position
    # Order: S1-Cu, S1-Au, S2-Cu, S2-Au, S3-Cu, S3-Au, S4-Cu, S4-Au
    species = np.array(["CU", "AU", "CU", "AU", "CU", "AU", "CU", "AU"], dtype=object)
    frac = np.repeat(O.X_SITES, 2, axis=0)  # each site has Cu and Au
    occ = np.array([0.75, 0.25] * 4)
    site_label = np.array(["S1", "S1", "S2", "S2", "S3", "S3", "S4", "S4"], dtype=object)
    cell_index = np.zeros((8, 3), dtype=np.int64)
    return Structure(lat, species, frac, model="average", occupancy=occ,
                     site_label=site_label, cell_index=cell_index,
                     supercell=(1, 1, 1), pbc=(True, True, True), min_separation=None)


def build_crystal(arm: str):
    """Build the crystal: repeat(average, (8,8,8)). B is set on the configuration after sampling."""
    avg = build_average_structure()
    crystal = avg.repeat((8, 8, 8))
    return crystal


def main():
    INPUTS.mkdir(exist_ok=True)
    files = {}

    # Draw 64 fresh seeds
    seeds = [secrets.randbits(63) for _ in range(K)]

    # Build crystals for both arms
    crystals = {"A": build_crystal("A"), "B": build_crystal("B")}

    # Write structures for both arms
    for arm in ("A", "B"):
        crystal = crystals[arm]
        for k in range(K):
            seed = seeds[k]
            config = crystal.sample_configuration(seed=seed)
            if arm == "B":
                # Set per-atom B: Cu 0.5, Au 0.8
                b_iso = np.where(config.species == "AU", O.B_AU_B, O.B_CU_B)
                config = config.replace(b_iso=b_iso, min_separation=None)
            stru_name = f"gate0_{arm}_{k:02d}.stru"
            stru_path = INPUTS / stru_name
            from discuspdf.discus_io import format_stru
            stru_path.write_text(format_stru(config, title=f"gate0_{arm}_{k:02d}_seed{seed}"))
            files[stru_name] = stru_path

        # Write macros
        for kind, aver, temp in (("total", "0.0", "temp ignore"), ("diffuse", "100.0", "temp use" if arm == "B" else "temp ignore")):
            mac_name = f"gate0_{arm}_{kind}.mac"
            mac_path = INPUTS / mac_name
            mac_path.write_text(MACRO.format(arm=arm, kind=kind, temp=temp, aver=aver,
                                            stru=f"gate0_{arm}_00.stru",  # placeholder; one macro per realization
                                            out=f"gate0_{arm}_{kind}_{k:02d}.h5"))
            files[mac_name] = mac_path

    # Compute predictions
    pred = {
        "schema": "gate0-v2-prereg-v1",
        "status": "PRE-REGISTERED: written before any engine run of these inputs that produced data",
        "design": {
            "lattice": "fcc", "a_A": O.A_CELL, "cells": [O.N_CELL] * 3,
            "atoms_per_cell": 4, "species": {"Cu": 0.75, "Au": 0.25},
            "B_iso": {"A": 0.0, "B": {"Cu": 0.5, "Au": 0.8}},
            "H_axis": {"first": float(O.H_AXIS[0]), "step": 1.0 / 8.0, "n": 25,
                        "last": float(O.H_AXIS[-1])},
            "seeds": seeds,
            "n_realizations": K,
        },
        "thresholds": {
            "E1_total_vs_realization_engine_relL2_max": 1e-9,
            "E2_diffuse_vs_realization_engine_relL2_max": 1e-6,
            "E3_diffuse_at_integer_h_max_over_max_diffuse": 1e-6,
            "E4_armB_log_shows_B_values": True,
            "E4_armA_log_shows_temp_ignore": True,
            "S1_mean_x_within": None,  # computed below
            "S2_var_x_within": None,   # computed below
            "S3_bonferroni_fwer": 1e-3,
            "S4_physics_vs_engine_rel_max": 1e-6,
        },
        "seeds": seeds,
        "n_realizations": K,
        "n_independent_set": O.n_independent_set(),
        "gamma_quantiles": {},
        "input_sha256": {},
        "code_sha256": {},
    }

    # Compute S1 and S2 thresholds
    n_S = pred["n_independent_set"]
    pred["thresholds"]["S1_mean_x_within"] = 5.0 / np.sqrt(K * n_S)
    pred["thresholds"]["S2_var_x_within"] = 5.0 * np.sqrt(8.0 / (K * n_S))

    # Compute Gamma quantiles for S3
    from scipy.stats import gamma as gamma_dist
    # For each voxel in the independent set, compute the two-sided Gamma(K, 1/K) interval
    # Bonferroni: alpha = 1e-3 / n_tested_voxels
    # For voxels with 2h integer (q ≡ -q mod 1), use Gamma(K/2, 2/K)
    mask_S = O.independent_set_mask()
    n_tested = int(mask_S.sum())
    alpha = 1e-3 / n_tested
    lo = gamma_dist.ppf(alpha / 2, K, scale=1.0 / K)
    hi = gamma_dist.ppf(1.0 - alpha / 2, K, scale=1.0 / K)
    pred["gamma_quantiles"]["S3_standard"] = [float(lo), float(hi)]
    # For 2h integer voxels: Gamma(K/2, 2/K)
    lo_2 = gamma_dist.ppf(alpha / 2, K / 2, scale=2.0 / K)
    hi_2 = gamma_dist.ppf(1.0 - alpha / 2, K / 2, scale=2.0 / K)
    pred["gamma_quantiles"]["S3_half_integer"] = [float(lo_2), float(hi_2)]

    # Compute expectations for both arms and both modes
    for arm in ("A", "B"):
        b_cu, b_au = (O.B_CU_A, O.B_AU_A) if arm == "A" else (O.B_CU_B, O.B_AU_B)
        for mode in ("physics", "engine"):
            E = O.expectation(mode, b_cu=b_cu, b_au=b_au)
            pred[f"E_{arm}_{mode}"] = O.sha256_array(E)

    # SHA-256 hashes
    pred["input_sha256"] = {name: O.sha256_file(p) for name, p in sorted(files.items())}
    pred["code_sha256"] = {n: O.sha256_file(HERE / n) for n in
                           ("oracle.py", "gate0_generate.py", "gate0_analyze.py", "gate0_selftest.py")}

    (HERE / "predictions.json").write_text(json.dumps(pred, indent=1, sort_keys=True) + "\n")
    print(f"Registered {K} seeds, {n_S} independent voxels")
    print(f"S1 threshold: {pred['thresholds']['S1_mean_x_within']:.6f}")
    print(f"S2 threshold: {pred['thresholds']['S2_var_x_within']:.6f}")
    print(f"S3 Gamma quantiles: {pred['gamma_quantiles']}")


if __name__ == "__main__":
    main()

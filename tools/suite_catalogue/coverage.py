"""Which DISCUS_SUITE commands discus-python can produce, measured against the catalogue.

    python tools/suite_catalogue/coverage.py [--write docs/SUITE_COVERAGE.md] [--check]

Two sources are walked through the catalogue's macro walker:

* **generated** — macros rendered by the package's own generators (``render_samples.py``):
  commands a user reaches through a typed discuspdf API;
* **used in evidence** — every committed ``*.mac`` file (probes, gates, fixtures): commands the
  project has run on a real engine, typed API or not.

Standard commands every menu shares (``exit``, ``echo``, ``help``...) are not counted.
"""

from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from discuspdf.suite_catalogue import load_catalogue  # noqa: E402


def used_commands(cat, texts):
    used = defaultdict(set)
    for text in texts:
        for step in cat.walk(text):
            if step.kind == "command":
                used[step.found_in].add(step.command)
    return used


def committed_macros():
    for path in sorted(ROOT.rglob("*.mac")):
        if ".git" not in path.parts:
            yield path.read_text(errors="replace")


def report(cat) -> str:
    from render_samples import sample_macros

    generated = used_commands(cat, [text for _label, text in sample_macros()])
    evidence = used_commands(cat, committed_macros())
    rows, totals = [], [set(), set(), set()]
    for path, menu in cat.menus.items():
        names = [c.name for c in menu.commands if not c.standard]
        if not names:
            continue
        g = [n for n in names if n in generated.get(path, ())]
        e = [n for n in names if n in evidence.get(path, ())]
        # patterson/inverse/diff-four are one routine: count its commands once in the totals
        for bucket, chosen in zip(totals, (names, g, e)):
            bucket.update((menu.routine, n) for n in chosen)
        rows.append(f"| `{path}` | {len(names)} | {len(g)} | {len(e)} | {', '.join(f'`{n}`' for n in g) or '—'} |")
    eng = cat.engine
    head = [
        "# DISCUS_SUITE command coverage",
        "",
        "Generated by `tools/suite_catalogue/coverage.py`; do not edit by hand.",
        f"Catalogue: DISCUS_SUITE {eng['version']} (`{eng['commit'][:7]}`), {len(cat.menus)} menus.",
        "",
        "- **Commands**: commands the menu's dispatcher accepts, without the standard ones every menu "
        "shares (`exit`, `echo`, `help`, `system`, ...).",
        "- **Generated**: emitted by a discuspdf macro generator (reachable through a typed API).",
        "- **In evidence**: used in at least one committed macro that ran on DISCUS (probes, gates, fixtures).",
        "",
        f"Totals: {len(totals[0])} commands, {len(totals[1])} generated, {len(totals[2])} in evidence "
        "(commands of one routine shown under several menus are counted once).",
        "",
        "| Menu | Commands | Generated | In evidence | Generated commands |",
        "|---|---:|---:|---:|---|",
    ]
    return "\n".join(head + rows) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", type=Path)
    ap.add_argument("--check", action="store_true", help="fail if --write file is out of date")
    a = ap.parse_args(argv)
    text = report(load_catalogue())
    if a.write and a.check:
        current = a.write.read_text() if a.write.exists() else ""
        if current != text:
            print(f"{a.write} is out of date; rerun with --write", file=sys.stderr)
            return 1
        return 0
    if a.write:
        a.write.write_text(text, newline="\n")
        print(f"wrote {a.write}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
